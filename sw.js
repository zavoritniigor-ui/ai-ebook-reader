self.addEventListener('activate', (event) => {
    event.waitUntil(
        caches.keys()
            .then((names) => Promise.all(
                names.filter((name) => name.startsWith('ai-reader-shell-') && name !== CACHE_NAME).map((name) => caches.delete(name))
            ))
            .then(() => self.clients.claim())
    );
});

// Chrome MUST NOT be handed a Response whose own `redirected` flag is true
// for a navigation FetchEvent — it silently fails the ENTIRE navigation with
// net::ERR_FAILED instead of displaying it (undocumented in MDN, but real and
// reproducible: this is exactly how the installed PWA shortcut broke —
// Cloudflare Pages 308-redirects /index.html -> /, so both a live fetch()
// of that URL and the copy `cache.addAll()` stored for it carry
// `redirected:true` forever, and every future navigation to that exact URL
// — including the shortcut's own start_url — hit this wall, online or off).
// Reconstructing a plain Response with the same body/status/headers has no
// redirect history and is always safe to hand to respondWith(); this heals
// it for ANY navigation URL, not just the one that prompted the fix, so an
// already-installed shortcut still pointed at the old /index.html start_url
// self-heals the moment this worker updates — no reinstall required.
async function stripRedirectHistory(res) {
    if (!res || !res.redirected) return res;
    return new Response(await res.clone().blob(), { status: res.status, statusText: res.statusText, headers: res.headers });
}

// Навігація (сам HTML-документ, включно зі стартом standalone-PWA) — мережа-спочатку
// з коротким таймаутом: онлайн-користувач завжди отримує code з сервера (а не вчорашню
// версію з кешу), офлайн чи повільна мережа — останню робочу закешовану. Саме тут жив
// ризик, що встановлений на планшеті PWA місяцями працює зі старою версією index.html.
async function networkFirstForNavigation(req) {
    const networkPromise = fetch(req).then((res) => {
        // Keep the installed offline HTML paired with its precached script versions.
        // A network navigation must not replace only one half of that snapshot.
        return res;
    }).catch(() => null);

    const timedOut = await Promise.race([
        networkPromise.then(() => false),
        new Promise((resolve) => setTimeout(() => resolve(true), NAVIGATION_TIMEOUT_MS))
    ]);

    if (!timedOut) {
        const res = await networkPromise;
        if (res && res.ok) return stripRedirectHistory(res);
    }

    // Мережа не встигла вчасно, впала або відповіла помилкою — власний кеш, а якщо
    // саме цього шляху там ще нема, фолбек на закешований index.html (той самий "app
    // shell" для будь-якої навігації). Only installing a complete new shell updates
    // the offline snapshot; online navigation still receives the network response.
    const cache = await caches.open(CACHE_NAME);
    const cached = (await cache.match(req)) || (await cache.match('./index.html')) || (await cache.match('./'));
    if (cached) return stripRedirectHistory(cached);
    const late = await networkPromise;
    if (late && late.ok) return stripRedirectHistory(late);
    return new Response('Offline', { status: 503, statusText: 'Offline' });
}

// «Поділитися → AI Reader» (share_target у manifest.webmanifest): Android надсилає POST із текстом і/або файлом книги.
// Кладемо їх у окремий кеш (його не чистить activate — там лише ai-reader-shell-*) і відкриваємо застосунок з ?shared=1;
// js/pwa-lifecycle.js забирає їх звідти й одразу видаляє. Без service worker той самий POST приймає functions/share-target.js.
const SHARE_CACHE = 'reader-share';
async function receiveShare(req) {
    const scope = self.registration.scope;
    try {
        const form = await req.formData();
        const field = (name) => String(form.get(name) || '').trim();
        const text = (field('text') || field('title')).slice(0, 5000);
        const file = form.getAll('book').find(f => f && typeof f === 'object' && f.size > 0 && f.size <= 300 * 1024 * 1024);
        const cache = await caches.open(SHARE_CACHE);
        for (const old of await cache.keys()) await cache.delete(old);
        if (file) await cache.put(new URL('__share/file', scope).href, new Response(file, { headers: {
            'content-type': file.type || 'application/octet-stream', 'x-name': encodeURIComponent(file.name || 'book') } }));
        if (text) await cache.put(new URL('__share/text', scope).href, new Response(text, { headers: { 'content-type': 'text/plain; charset=utf-8' } }));
        return Response.redirect(new URL('./?shared=' + (file || text ? '1' : 'empty'), scope).href, 303);
    } catch (e) {
        return Response.redirect(new URL('./?shared=error', scope).href, 303);
    }
}

self.addEventListener('fetch', (event) => {
    const req = event.request;
    if (req.method === 'POST' && new URL(req.url).pathname === new URL('./share-target', self.registration.scope).pathname) {
        event.respondWith(receiveShare(req));
        return;
    }

    // Ніколи не чіпаємо нічого, крім звичайного GET, і ніколи — чужі домени.
    // Це і є той бар'єр, що не дає в кеш потрапити запитам до AI/перекладу чи
    // будь-чому, що несе API-ключ чи відповідь моделі.
    if (req.method !== 'GET') return;
    const url = new URL(req.url);
    if (url.origin !== self.location.origin) return;

    if (req.mode === 'navigate') {
        event.respondWith(networkFirstForNavigation(req));
        return;
    }

    // Only the declared shell is cacheable; API requests and arbitrary same-origin
    // resources never enter this cache. Query versions prevent old JS/new HTML mixes.
    const shellUrls = APP_SHELL.map(path => new URL(path, self.location.href).href);
    if (!shellUrls.includes(url.href)) return;
    event.respondWith(caches.open(CACHE_NAME).then(async cache => {
        const cached = await cache.match(req);
        return cached || fetch(req);
    }));
});
