"""Build js/cefr-lexicon-data.js: CEFR levels of English and French words for the reading statistics.

Sources (downloaded on every run, nothing else is stored in the repo):
- English: CEFR-J Vocabulary Profile 1.5 (Tono Laboratory, TUFS; free for research and commercial use with citation)
  + Octanove Vocabulary Profile C1/C2 1.0 (Octanove Labs, CC BY-SA 4.0), via github.com/openlanguageprofiles/olp-en-cefrj.
- French: FLELex TT Beacco (François et al. 2014, Pintard & François 2020; CENTAL, UCLouvain; CC BY-NC-SA 4.0).
A word listed under several parts of speech keeps its lowest (easiest) level. Multi-word entries are skipped.
"""
import csv, io, json, urllib.request
from pathlib import Path

LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2']
OLP = 'https://raw.githubusercontent.com/openlanguageprofiles/olp-en-cefrj/master/'
FLELEX = 'https://cental.uclouvain.be/cefrlex/static/resources/fr/FleLex_TT_Beacco.tsv'


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as res:
        return res.read().decode('utf-8-sig')


def keep(table, word, level):
    word = word.strip().lower()
    if not word or ' ' in word or level not in LEVELS or not any(ch.isalpha() for ch in word):
        return
    if word not in table or LEVELS.index(level) < LEVELS.index(table[word]):
        table[word] = level


en = {}
for name in ('cefrj-vocabulary-profile-1.5.csv', 'octanove-vocabulary-profile-c1c2-1.0.csv'):
    for row in csv.DictReader(io.StringIO(fetch(OLP + name))):
        for word in row['headword'].split('/'):
            keep(en, word, row['CEFR'].strip().upper())
fr = {}
for row in csv.DictReader(io.StringIO(fetch(FLELEX)), delimiter='\t'):
    keep(fr, row['word'], (row.get('level') or '').strip().upper())

data = {lang: {level: ' '.join(sorted(w for w, l in table.items() if l == level)) for level in LEVELS} for lang, table in (('en', en), ('fr', fr))}
out = Path(__file__).resolve().parents[1] / 'js' / 'cefr-lexicon-data.js'
out.write_text(
    '/* Generated by tools/build_cefr_lexicon.py — do not edit by hand.\n'
    ' * English: CEFR-J Vocabulary Profile 1.5 (Tono Laboratory, Tokyo University of Foreign Studies, http://www.cefr-j.org/)\n'
    ' *   and Octanove Vocabulary Profile C1/C2 1.0 (Octanove Labs, CC BY-SA 4.0), via Open Language Profiles.\n'
    ' * French: FLELex (François, Gala, Watrin & Fairon 2014; Pintard & François 2020; CENTAL, UCLouvain),\n'
    ' *   CC BY-NC-SA 4.0, https://cental.uclouvain.be/cefrlex/flelex/ */\n'
    'const CEFR_LEXICON = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print({lang: {l: len(v.split()) for l, v in d.items()} for lang, d in data.items()}, out.stat().st_size, 'bytes')
