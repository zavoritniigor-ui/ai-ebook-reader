"""Regenerate js/offline-catalog.js: the pinned list of Mozilla's translation models the offline translator may download.

    python3 tools/offline_models_catalog.py            # rewrite js/offline-catalog.js from Mozilla's current records
    python3 tools/offline_models_catalog.py --engine   # also (re)download the engine (wasm + glue) into vendor/bergamot-<version>/

Needs the network. The app never reads Mozilla's records itself: every file it may fetch (address, size, SHA-256) is pinned
in the generated catalog, so a download is verified byte for byte and a changed upstream cannot alter what the app installs.
Per language pair the highest STABLE version that has a complete file set is taken (alpha/beta versions are skipped).
"""
import hashlib, json, re, sys, urllib.request
from pathlib import Path

root = Path(__file__).resolve().parents[1]
RECORDS = 'https://firefox.settings.services.mozilla.com/v1/buckets/main/collections/%s/records?_limit=2000'
ENGINE_VERSION = '3.0'
# The in-tree glue that Firefox itself loads next to this engine (bergamot-translator v0.6.0, MPL-2.0).
GLUE_URL = 'https://raw.githubusercontent.com/mozilla/gecko-dev/c7818d570e8e3a5d326483f62276b7b2494b72ed/toolkit/components/translations/bergamot-translator/%s'
CDN = 'https://firefox-settings-attachments.cdn.mozilla.net/'
# The app's language codes where Mozilla's differ.
CODES = {'zh': 'zh-Hans'}
# Languages the app can read or translate into (js/core.js LANGUAGE_CONFIG + js/lang-detect.js LATIN_LANG_LOCALES). Mozilla has no Irish.
LANGS = {'en', 'fr', 'es', 'de', 'it', 'pt', 'nl', 'pl', 'uk', 'ru', 'zh-Hans', 'ko', 'hi'}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={'user-agent': 'ai-ebook-reader-catalog'}), timeout=60) as r:
        return r.read()


def records(collection):
    return json.loads(get(RECORDS % collection))['data']


def version_key(v):
    return tuple(int(x) for x in v.split('.'))


def pick(recs):
    """The newest stable version whose files form a complete model: model + shortlist + one shared vocabulary or a source/target pair."""
    by_version = {}
    for r in recs:
        if re.fullmatch(r'\d+\.\d+', r['version']):
            by_version.setdefault(r['version'], {})[r['fileType']] = r
    for version in sorted(by_version, key=version_key, reverse=True):
        files = by_version[version]
        vocab = ('vocab',) if 'vocab' in files else ('srcvocab', 'trgvocab')
        if 'model' in files and 'lex' in files and all(v in files for v in vocab):
            return version, [files[t] for t in ('model', 'lex') + vocab]
    return None


def build_models():
    pairs = {}
    for r in records('translations-models'):
        if r['fromLang'] in LANGS and r['toLang'] in LANGS:
            pairs.setdefault((r['fromLang'], r['toLang']), []).append(r)
    models = {}
    for (src, tgt), recs in sorted(pairs.items()):
        chosen = pick(recs)
        if not chosen:
            continue
        version, files = chosen
        models[f'{src}>{tgt}'] = {
            'version': version,
            'gemm': 'int8shiftAll' if files[0]['name'].endswith('intgemm8.bin') else 'int8shiftAlphaAll',
            'files': [{'type': f['fileType'], 'path': f['attachment']['location'], 'size': f['attachment']['size'],
                       'sha256': f['attachment']['hash']} for f in files]}
    return models


def engine_record():
    for r in records('translations-wasm'):
        if r['name'] == 'bergamot-translator' and r['version'] == ENGINE_VERSION:
            return r
    raise SystemExit(f'bergamot-translator {ENGINE_VERSION} is not in translations-wasm any more')


def main():
    engine = engine_record()
    folder = f'vendor/bergamot-{ENGINE_VERSION}'
    wasm = {'path': f'{folder}/bergamot-translator.wasm', 'size': engine['attachment']['size'], 'sha256': engine['attachment']['hash']}
    if '--engine' in sys.argv:
        (root / folder).mkdir(parents=True, exist_ok=True)
        data = get(CDN + engine['attachment']['location'])
        assert hashlib.sha256(data).hexdigest() == wasm['sha256'] and len(data) == wasm['size'], 'engine download does not match its record'
        (root / wasm['path']).write_bytes(data)
        for name in ('bergamot-translator.js', 'LICENSE'):
            (root / folder / name).write_bytes(get(GLUE_URL % name))
    elif not (root / wasm['path']).is_file():
        raise SystemExit(f'{wasm["path"]} is missing: run with --engine once')
    elif hashlib.sha256((root / wasm['path']).read_bytes()).hexdigest() != wasm['sha256']:
        raise SystemExit(f'{wasm["path"]} differs from Mozilla\'s record: run with --engine')
    models = build_models()
    dump = lambda v: json.dumps(v, sort_keys=True)   # one line per entry: the catalog stays reviewable and small
    lines = ['// GENERATED by tools/offline_models_catalog.py from Mozilla Remote Settings (collections translations-models, translations-wasm). Do not edit.',
             '// The offline translator (js/offline-translate.js) downloads ONLY these files, through /api/offline-model, and checks every size and SHA-256.',
             'const OFFLINE_CATALOG = {',
             f'    engine: {dump({"version": ENGINE_VERSION, "glue": f"{folder}/bergamot-translator.js", "wasm": wasm})},',
             f'    codes: {dump(CODES)},',
             '    models: {']
    for key, m in models.items():
        lines.append(f'        {dump(key)}: {{ version: {dump(m["version"])}, gemm: {dump(m["gemm"])}, files: [')
        lines += [f'            {dump(f)},' for f in m['files']]
        lines.append('        ] },')
    lines += ['    }', '};', '']
    (root / 'js/offline-catalog.js').write_text('\n'.join(lines))
    total = sum(f['size'] for m in models.values() for f in m['files'])
    print(f'{len(models)} models, {total / 1e6:.0f} MB in all, engine {ENGINE_VERSION}')


main()
