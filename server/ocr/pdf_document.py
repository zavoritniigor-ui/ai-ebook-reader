"""Permissively licensed PDF generation and N-up assembly (ReportLab + pypdf)."""
import io
import os
import threading

from pypdf import PdfReader, PdfWriter, Transformation
from reportlab.lib.utils import ImageReader
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen.canvas import Canvas

FONT = os.getenv("OCR_FONT", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
MAX_OUTPUT_BYTES = 100 * 1024 * 1024
_font_lock = threading.Lock()


class OutputLimit(ValueError):
    pass


class BoundedBuffer(io.BytesIO):
    def write(self, data):
        if self.tell() + len(data) > MAX_OUTPUT_BYTES:
            raise OutputLimit("Document exceeds the 100 MiB PDF limit")
        return super().write(data)


def render_pdf(image, words):
    with _font_lock:
        if "OCRUnicode" not in pdfmetrics.getRegisteredFontNames():
            pdfmetrics.registerFont(TTFont("OCRUnicode", FONT))
    face = pdfmetrics.getFont("OCRUnicode").face
    ascent, descent = face.ascent / 1000, face.descent / 1000
    width, height = image.size
    scale = 842 / max(width, height)
    buffer = BoundedBuffer()
    canvas = Canvas(buffer, pagesize=(width * scale, height * scale), pageCompression=1)
    canvas.setProducer("AI E-book Reader OCR server")
    canvas.drawImage(ImageReader(image), 0, 0, width * scale, height * scale)
    for word in words:
        left, top, right, bottom = (value * scale for value in word["bbox"])
        size = (bottom - top) / (ascent - descent)
        measured = pdfmetrics.stringWidth(word["text"], "OCRUnicode", size)
        if size <= 0 or measured <= 0:
            continue
        text = canvas.beginText()
        text.setFont("OCRUnicode", size)
        text.setTextRenderMode(3)
        text.setHorizScale(100 * (right - left) / measured)
        text.setTextOrigin(left, height * scale - top - ascent * size)
        text.textOut(word["text"] + " ")
        canvas.drawText(text)
    canvas.showPage()
    canvas.save()
    return buffer.getvalue()


def sheet_layout(pages, paper, nup):
    width, height = (595.28, 841.89) if paper == "a4" else (612, 792)
    margin, gap = 18, 9
    best = None
    for landscape in (False, True):
        w, h = (height, width) if landscape else (width, height)
        for columns in range(1, nup + 1):
            if nup % columns:
                continue
            rows = nup // columns
            cw, ch = (w - 2 * margin - (columns - 1) * gap) / columns, (h - 2 * margin - (rows - 1) * gap) / rows
            scales = [min(cw / float(p.mediabox.width), ch / float(p.mediabox.height)) for p in pages]
            score = sum((float(p.mediabox.width) * s) * (float(p.mediabox.height) * s) for p, s in zip(pages, scales))
            # Preserve portrait unless landscape provides a meaningful improvement.
            if best is None or score > best[0] * (1.1 if landscape and not best[1] else 1):
                best = (score, landscape, w, h, columns, cw, ch, scales)
    _, _, width, height, columns, cw, ch, scales = best
    cells = []
    for index, (page, scale) in enumerate(zip(pages, scales)):
        dw, dh = float(page.mediabox.width) * scale, float(page.mediabox.height) * scale
        left = margin + index % columns * (cw + gap) + (cw - dw) / 2
        bottom = height - margin - index // columns * (ch + gap) - (ch + dh) / 2
        cells.append((scale, left, bottom))
    return width, height, cells


def assemble(paths, paper, nup):
    # Input PDFs are generated by this process, never supplied by the client.
    if sum(path.stat().st_size for path in paths) > MAX_OUTPUT_BYTES - 1024 * 1024:
        raise OutputLimit("Document exceeds the 100 MiB PDF limit")
    readers = [PdfReader(path) for path in paths]
    writer = PdfWriter()
    for start in range(0, len(readers), nup):
        pages = [reader.pages[0] for reader in readers[start:start + nup]]
        if paper == "fit":
            writer.add_page(pages[0])
            continue
        width, height, cells = sheet_layout(pages, paper, nup)
        sheet = writer.add_blank_page(width, height)
        for page, (scale, left, bottom) in zip(pages, cells):
            sheet.merge_transformed_page(page, Transformation().scale(scale).translate(left, bottom))
    output = BoundedBuffer()
    writer.write(output)
    return output.getvalue()
